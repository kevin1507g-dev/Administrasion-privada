-- Prueba de llamada: solo al teléfono verificado del propio Sistema Admin.
-- No llama a residentes, no activa relés, no expone números ni crea autorizaciones de acceso.
create table if not exists access_private.interfon_voice_pruebas (
 id bigint generated by default as identity primary key,
 usuario_id uuid not null references public.profiles(id) on delete cascade,
 telefono_id uuid not null references access_private.interfon_telefonos(id) on delete cascade,
 creado_at timestamptz not null default now()
);
create index if not exists interfon_voice_pruebas_limite_idx
 on access_private.interfon_voice_pruebas(usuario_id,creado_at desc);
alter table access_private.interfon_voice_pruebas enable row level security;
revoke all on access_private.interfon_voice_pruebas from public,anon,authenticated;

create or replace function public.interfon_voice_prueba_preparar(p_usuario uuid)
returns jsonb language plpgsql security definer set search_path=''
as $fn$
declare
 v access_private.interfon_telefonos%rowtype;
 v_cantidad int;
 v_ultima timestamptz;
 v_clave text;
 v_numero text;
begin
 if p_usuario is null or not exists (
  select 1 from public.profiles
  where id=p_usuario and rol='owner' and activo is true and estado_registro='aprobado'
 ) then raise exception 'Solo Sistema Admin aprobado puede iniciar una prueba de llamada.'; end if;
 select * into v from access_private.interfon_telefonos
 where destino='sistema_admin' and slot='sistema_admin'
 and registrado_por=p_usuario and verificado_at is not null
 limit 1;
 if v.id is null then raise exception 'Verifica primero tu celular de Sistema Admin.'; end if;
 if v.tipo <> 'movil' then raise exception 'La prueba inicial requiere un celular verificado.'; end if;
 perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtext('interfon-voice:'||p_usuario::text));
 select count(*),max(creado_at) into v_cantidad,v_ultima
 from access_private.interfon_voice_pruebas
 where usuario_id=p_usuario and creado_at>now()-interval '24 hours';
 if v_cantidad>=3 then
  raise exception 'Máximo tres llamadas de prueba en 24 horas.';
 end if;
 if v_ultima>now()-interval '3 minutes' then
  raise exception 'Espera tres minutos entre llamadas de prueba.';
 end if;
 select decrypted_secret into v_clave from vault.decrypted_secrets
 where name='interfon_tel_cipher_v1';
 if nullif(v_clave,'') is null then raise exception 'Servicio de cifrado no disponible.'; end if;
 v_numero:=extensions.pgp_sym_decrypt(v.numero_cifrado,v_clave);
 if v_numero !~ '^\+52[0-9]{10}$' then raise exception 'Número del contacto inválido.'; end if;
 insert into access_private.interfon_voice_pruebas(usuario_id,telefono_id)
 values(p_usuario,v.id);
 return jsonb_build_object(
  'numero',v_numero,
  'ultimos4',v.numero_ultimos4,
  'verificado',true
 );
end $fn$;
revoke all on function public.interfon_voice_prueba_preparar(uuid) from public,anon,authenticated;
grant execute on function public.interfon_voice_prueba_preparar(uuid) to service_role;
comment on table access_private.interfon_voice_pruebas is
 'Contador de llamadas de prueba realizadas manualmente a Sistema Admin; no abre portones ni llama a residentes.';
